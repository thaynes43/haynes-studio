import { execFileSync } from "node:child_process";
import { resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";
import { writeFile } from "node:fs/promises";

const [schemaPath] = process.argv.slice(2);
const schema = schemaPath
  ? pathToFileURL(resolve(schemaPath))
  : JSON.parse(execFileSync("uv", ["run", "--locked", "studio-api", "openapi"], {
      cwd: fileURLToPath(new URL("../../", import.meta.url)),
      encoding: "utf8",
      maxBuffer: 16 * 1024 * 1024,
    }));

const ast = await openapiTS(schema);
const header = "// Generated by pnpm generate:api from studio-api OpenAPI. Do not edit.\n\n";
await writeFile(new URL("../src/api/schema.ts", import.meta.url), header + astToString(ast));
